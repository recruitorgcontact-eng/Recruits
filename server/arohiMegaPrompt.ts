export function sanitizeSpeechText(rawText: string): string {
  return String(rawText || "")
    .replace(/\[(.*?)\]\((.*?)\)/g, "$1")
    .replace(/[*_#`~]+/g, "")
    .replace(
      /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE00}-\u{FE0F}\u{200D}]/gu,
      ""
    )
    .replace(/•/g, ", ")
    .replace(/\s+/g, " ")
    .trim();
}

export function buildArohiLiveSystemInstruction(options?: {
  language?: string;
  memory?: any;
  interviewContext?: {
    role?: string;
    level?: string;
    topic?: string;
    isStressMode?: boolean;
  };
}): string {
  const langCode = options?.language || "en";
  const langLabel = ALL_INDIAN_LANGUAGE_NAMES[langCode] || "Indian English";
  const parts: string[] = [
    AROHI_MEGA_PROMPT,
    `\nCURRENT SESSION CONTEXT:\n- Initial Selected UI Language: ${langLabel} (code: ${langCode}). Mirror any Indian language or dialect the candidate switches to immediately.`,
  ];

  if (options?.memory) {
    const m = options.memory;
    const summary = {
      name: m.personalInfo?.fullName || undefined,
      location: m.personalInfo?.location || undefined,
      targetRole: m.targetRole || undefined,
      experienceLevel: m.experienceLevel || undefined,
      skills: Array.isArray(m.skills) ? m.skills.slice(0, 12) : undefined,
      resumeScore: typeof m.resumeScore === "number" ? m.resumeScore : undefined,
    };
    parts.push(`- Candidate Profile Context: ${JSON.stringify(summary)}`);
  }

  if (options?.interviewContext?.role) {
    const ic = options.interviewContext;
    parts.push(
      `- Active Mode: LIVE VOICE MOCK INTERVIEW SIMULATOR. Target Role: "${ic.role}", Level: "${ic.level || "Mid Level"}", Focus Topic: "${ic.topic || "Technical & Behavioral"}", Stress Mode: ${ic.isStressMode ? "High Pressure Panel" : "Supportive Coaching"}.\nConduct a natural, realistic one-question-at-a-time mock interview in the candidate's spoken Indian language (or bilingual bridging if requested). After each full answer, give warm encouraging reinforcement, 2 crisp improvements, and ask the next realistic question.`
    );
  }

  return parts.join("\n");
}

